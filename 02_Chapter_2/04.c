/*3.Control Instruction
Used to control the flow/order in which statements execute.*/

/*Sequence Control Instruction – Executes statements one after another in order.
Example: a = 10; b = 20;

Decision Control Instruction – Makes decisions based on conditions.
Examples: if, if-else, switch

Loop Control Instruction – Repeats a set of statements.
Examples: for, while, do-while

Case Control Instruction – Selects one option from multiple cases.
Example: switch-case*/