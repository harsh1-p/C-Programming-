/*In C programming, an operator is a symbol that tells the computer to perform an operation on one or more values (called operands).*/

/*
Types of operators in C

Arithmetic operators – +, -, *, /, %
Relational operators – >, <, >=, <=, ==, !=
Logical operators – &&, ||, !
Assignment operators – =, +=, -=, *=, /=, %=
Increment/Decrement operators – ++, --
Bitwise operators – &, |, ^, ~, <<, >>
Conditional (ternary) operator – ?:
Special operators – sizeof, &, *, ., ->, etc

*/